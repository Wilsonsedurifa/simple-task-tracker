import assert from 'node:assert/strict';

export async function appNotificationChecks(page, browser, base) {
    await page.setViewportSize({ width: 1280, height: 950 });
    let reads = 0;
    const count = request => { if (request.method() === 'GET' && new URL(request.url()).pathname === '/api/tasks') reads++; };
    page.on('request', count);
    await page.goto(base + '/notifications');
    await page.waitForFunction(() => document.querySelector('#app-notification-feed')?.getAttribute('aria-busy') === 'false');
    assert.equal(reads, 1);
    assert.equal(await page.locator('#app-notification-feed [data-app-notification-id]').count(), 4);
    assert.equal(await page.locator('#app-notification-bell [data-app-unread]').textContent(), '4');
    assert.equal(await page.locator('#sidebar [data-app-notifications] [data-app-unread]').textContent(), '4');
    const userId = await page.locator('body').getAttribute('data-app-user-id'), key = 'app-notifications-read:' + userId;
    await page.locator('#app-notification-tab-unread').click();
    const first = page.locator('#app-notification-feed [data-app-notification-id]').first(), id = await first.getAttribute('data-app-notification-id');
    assert.match(await first.textContent(), /2 days overdue/);
    await first.click();
    assert.equal(await page.locator('#detail-title').textContent(), 'Review task 0');
    assert.equal(await page.locator('#app-notification-bell [data-app-unread]').textContent(), '3');
    assert.ok(await page.evaluate(({ key, id }) => JSON.parse(localStorage.getItem(key)).ids.includes(id), { key, id }));
    await page.keyboard.press('Escape'); await page.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await page.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'app-notification-tab-unread');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#app-notification-feed')?.getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#app-notification-bell [data-app-unread]').textContent(), '3');
    await page.evaluate(() => { window.scrollTo(0, 0); document.activeElement?.blur(); });
    await page.screenshot({ path: 'storage/app/ui-review/notifications-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 380, height: 950 });
    await page.screenshot({ path: 'storage/app/ui-review/notifications-mobile.png', fullPage: true });
    const before = reads;
    await page.locator('.app-notifications-toolbar [data-app-mark-all]').click();
    assert.equal(await page.locator('#app-notification-bell [data-app-unread]').isVisible(), false);
    await page.locator('#app-notification-tab-all').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#app-notification-tab-unread').getAttribute('aria-selected'), 'true');
    await page.locator('#app-notification-feed').getByText('Wala kang bagong notifications.', { exact: true }).waitFor();
    await page.setViewportSize({ width: 1280, height: 950 });
    await page.locator('#app-notification-bell').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#app-notification-bell').getAttribute('aria-expanded'), 'true');
    assert.equal(await page.locator('#app-notification-preview [data-app-notification-id]').count(), 4);
    assert.ok(await page.evaluate(() => document.activeElement.hasAttribute('data-app-notification-id')));
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Escape'); await page.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    assert.equal(await page.locator('#app-notification-bell').getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'app-notification-bell');
    await page.locator('#app-notification-bell').click();
    await page.mouse.click(4, 300);
    await page.waitForFunction(() => document.querySelector('#app-notification-bell').getAttribute('aria-expanded') === 'false');
    assert.equal(reads, before, 'read/filter/dropdown actions never fetch tasks');
    await page.locator('#app-notification-bell').click();
    await page.locator('#app-notification-view-all').click();
    await page.waitForFunction(() => document.querySelector('#app-notification-feed')?.getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#app-notification-bell [data-app-unread]').isVisible(), false);
    page.off('request', count);
    const dueToday = page.locator('#app-notification-feed [data-app-notification-id]').filter({ hasText: 'Review task 1' });
    await dueToday.click();
    const updatingId = new URL(page.url()).searchParams.get('task');
    await page.route('**/api/tasks/' + updatingId + '/complete', async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.continue(); });
    const completed = page.waitForResponse(response => response.url().endsWith('/api/tasks/' + updatingId + '/complete'));
    await page.locator('#detail-complete-btn').click();
    assert.equal(await page.locator('body').getAttribute('data-app-unread-count'), '1', 'optimistic completion replaces read due reminder with new completion notice');
    await completed;
    await page.unroute('**/api/tasks/' + updatingId + '/complete');
    await page.waitForFunction(() => !document.querySelector('#detail-complete-btn').disabled);
    const reopened = page.waitForResponse(response => response.url().endsWith('/api/tasks/' + updatingId + '/reopen'));
    await page.locator('#detail-complete-btn').click();
    assert.equal(await page.locator('body').getAttribute('data-app-unread-count'), '0');
    await reopened;
    await page.waitForFunction(() => !document.querySelector('#detail-complete-btn').disabled);
    await page.keyboard.press('Escape'); await page.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await page.waitForFunction(() => !document.querySelector('#app-task-dialog').open);

    const context = await browser.newContext({ storageState: await page.context().storageState(), viewport: { width: 1280, height: 950 }, timezoneId: 'America/New_York' });
    const review = await context.newPage(), errors = [], consoleProblems = [];
    review.on('pageerror', failure => errors.push(failure.message));
    review.on('console', message => { if (['error', 'warning'].includes(message.type())) consoleProblems.push(message.text()); });
    await review.clock.install({ time: new Date('2026-10-15T16:00:00Z') });
    let fixture = Array.from({ length: 14 }, (_, index) => ({ id: 1000 + index, title: index === 0 ? 'Buy rice <b>safe</b> and vegetables' : 'Notification task ' + index, description: 'Derived reminder details', priority: ['high', 'medium', 'low'][index % 3], status: index < 9 ? 'pending' : 'completed', stage: 'todo', due_date: index < 3 ? '2026-10-13' : index < 6 ? '2026-10-15' : index < 9 ? '2026-10-16' : null, completed_at: index < 9 ? null : index === 13 ? new Date('2026-10-14T22:00:00Z').getTime() : new Date('2026-10-15T16:00:00Z').getTime() - (index - 8) * 3600000, created_at: '2026-10-01T12:00:00Z' }));
    let release;
    const gate = new Promise(resolve => { release = resolve; });
    await review.route('**/api/tasks?sort=deadline', async route => { await gate; await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(fixture) }); });
    await review.goto(base + '/notifications');
    assert.equal(await review.locator('#app-notification-feed').getAttribute('aria-busy'), 'true');
    assert.equal(await review.locator('#app-notification-feed .app-task-skeleton').count(), 3);
    release();
    await review.waitForFunction(() => document.querySelectorAll('#app-notification-feed [data-app-notification-id]').length === 14);
    assert.equal(await review.locator('#app-notification-bell [data-app-unread]').textContent(), '9+');
    assert.equal(await review.locator('#app-notification-bell').getAttribute('aria-label'), 'Notifications, 14 unread');
    assert.equal(await review.locator('#sidebar [data-app-notifications] [data-app-unread]').textContent(), '9+');
    assert.deepEqual(await review.locator('.app-notification-group-title').evaluateAll(nodes => nodes.map(node => node.firstChild.textContent)), ['Today', 'Yesterday']);
    const unsafe = review.locator('#app-notification-feed [data-task-id="1000"]');
    assert.ok((await unsafe.textContent()).includes('<b>safe</b>'));
    assert.equal(await unsafe.locator('b').count(), 0);
    await review.locator('#app-notification-bell').click();
    assert.deepEqual(await review.locator('#app-notification-preview [data-task-id]').evaluateAll(nodes => nodes.map(node => Number(node.dataset.taskId))), [1000, 1009, 1010, 1011, 1012]);
    await review.locator('#app-notification-preview [data-task-id="1012"]').click();
    assert.equal(await review.locator('#detail-title').textContent(), 'Notification task 12');
    assert.equal(await review.locator('#app-notification-bell').getAttribute('aria-label'), 'Notifications, 13 unread');
    await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await review.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    assert.equal(await review.evaluate(() => document.activeElement.id), 'app-notification-bell');
    for (const theme of ['light', 'dark', 'system', 'kawaii', 'racing']) {
        await review.setViewportSize({ width: 1280, height: 950 });
        await review.locator('#theme-toggle').click();
        await review.locator('.app-theme-option[data-app-mode="' + theme + '"]').click();
        await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
        await review.emulateMedia({ reducedMotion: 'reduce' });
        for (const width of [380, 768, 1024, 1280, 1920]) {
            await review.setViewportSize({ width, height: 950 });
            await review.locator(width < 768 ? '#app-more-button' : '#app-notification-bell').click();
            const box = await review.locator(width < 768 ? '#app-more' : '#app-notification-dropdown').boundingBox();
            assert.ok(box && box.x >= 0 && box.x + box.width <= width + 1 && box.y + box.height <= 951, theme + ' dropdown fits at ' + width);
            assert.equal(await review.locator('#app-notification-preview [data-app-notification-id]').count(), 5);
            await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
            assert.equal(await review.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
        }
    }
    await review.setViewportSize({ width: 1280, height: 950 });
    await review.emulateMedia({ reducedMotion: 'no-preference' });
    await review.locator('#app-notification-bell').click();
    await review.locator('#app-notification-dropdown [data-app-mark-all]').click();
    assert.equal(await review.locator('#app-notification-bell').getAttribute('aria-expanded'), 'true');
    assert.ok(await review.evaluate(() => document.activeElement.hasAttribute('data-app-notification-id')));
    await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await review.reload();
    await review.waitForFunction(() => document.querySelectorAll('#app-notification-feed [data-app-notification-id]').length === 14);
    assert.equal(await review.locator('#app-notification-bell [data-app-unread]').isVisible(), false);
    await review.clock.fastForward(13 * 3600000);
    await review.waitForFunction(() => [...document.querySelectorAll('#app-notification-feed [data-app-notification-id]')].every(node => node.dataset.appNotificationId.endsWith(':2026-10-16')));
    assert.equal(await review.locator('#app-notification-bell').getAttribute('aria-label'), 'Notifications, 13 unread', 'new local day creates fresh IDs and expires old completions');

    const otherTab = await context.newPage();
    await otherTab.clock.install({ time: new Date('2026-10-16T05:00:00Z') });
    await otherTab.route('**/api/tasks?sort=deadline', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(fixture) }));
    await otherTab.goto(base + '/notifications');
    await otherTab.waitForFunction(() => document.querySelectorAll('#app-notification-feed [data-app-notification-id]').length === 13);
    await otherTab.locator('.app-notifications-toolbar [data-app-mark-all]').click();
    await review.waitForFunction(() => document.body.dataset.appUnreadCount === '0');
    await otherTab.close();

    const identity = await review.locator('body').getAttribute('data-app-user-id'), ownKey = 'app-notifications-read:' + identity;
    const ownReadState = await review.evaluate(key => localStorage.getItem(key), ownKey);
    const isolated = await browser.newContext({ storageState: { ...(await context.storageState()), cookies: [] }, timezoneId: 'America/New_York' });
    const userB = await isolated.newPage();
    await userB.clock.install({ time: new Date('2026-10-16T05:00:00Z') });
    await userB.route('**/api/tasks?sort=deadline', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(fixture) }));
    await userB.goto(base + '/register');
    await userB.locator('#name').fill('Notification Other User');
    await userB.locator('#email').fill('notifications-' + process.pid + '-' + Date.now() + '@example.test');
    await userB.locator('#password').fill('Notify-test-123!');
    await userB.locator('[data-register-form] button[type="submit"]').click();
    await userB.waitForURL('**/continue');
    await userB.getByRole('button', { name: 'Continue', exact: true }).click();
    await userB.waitForURL('**/dashboard');
    await userB.goto(base + '/notifications');
    await userB.waitForFunction(() => document.body.dataset.appUnreadCount === '13');
    const otherIdentity = await userB.locator('body').getAttribute('data-app-user-id');
    assert.notEqual(otherIdentity, identity);
    await userB.locator('.app-notifications-toolbar [data-app-mark-all]').click();
    assert.equal(await userB.evaluate(key => localStorage.getItem(key), ownKey), ownReadState, 'another account never overwrites this user’s reads');
    assert.ok(await userB.evaluate(id => localStorage.getItem('app-notifications-read:' + id), otherIdentity));
    await isolated.close();

    fixture = [{ ...fixture[0], id: 4000, title: 'DST milestone', status: 'completed', due_date: null, completed_at: '2026-03-08T04:30:00Z' }];
    await review.clock.setSystemTime(new Date('2026-03-09T04:15:00Z'));
    await review.reload();
    await review.waitForFunction(() => document.querySelectorAll('#app-notification-feed [data-app-notification-id]').length === 1);
    assert.deepEqual(await review.locator('.app-notification-group-title').evaluateAll(nodes => nodes.map(node => node.firstChild.textContent)), ['Earlier'], 'a spring-DST 24-hour window can reach two local dates back');
    assert.deepEqual(errors, []); assert.deepEqual(consoleProblems, []);
    fixture = [{ ...fixture[0], id: 4001, title: 'Notification rollback task', status: 'pending', due_date: '2026-03-07', completed_at: null }];
    await review.reload();
    await review.waitForFunction(() => document.body.dataset.appUnreadCount === '1');
    await review.locator('#app-notification-feed [data-app-notification-id]').click();
    await review.route('**/api/tasks/4001/complete', async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ message: 'Notification rollback test' }) }); });
    await review.locator('#detail-complete-btn').click();
    assert.equal(await review.locator('body').getAttribute('data-app-unread-count'), '1');
    await review.getByText('Notification rollback test', { exact: true }).waitFor();
    assert.equal(await review.locator('body').getAttribute('data-app-unread-count'), '0', 'failed completion restores the prior read reminder');
    await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await review.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    await review.unroute('**/api/tasks?sort=deadline');
    await review.route('**/api/tasks?sort=deadline', route => route.abort('failed'));
    await review.reload();
    await review.locator('#app-notification-error').getByRole('button', { name: 'Try again' }).waitFor();
    await review.locator('#app-notification-bell').click();
    await review.locator('#app-notification-preview-error').getByRole('button', { name: 'Try again' }).waitFor();
    await review.unroute('**/api/tasks?sort=deadline');
    await review.route('**/api/tasks?sort=deadline', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
    await review.locator('#app-notification-preview-error').getByRole('button', { name: 'Try again' }).click();
    await review.locator('#app-notification-preview').getByText('Wala kang bagong notifications.', { exact: true }).waitFor();
    assert.equal(await review.locator('#app-notification-bell [data-app-unread]').isVisible(), false);
    await context.close();

    const blockedContext = await browser.newContext({ storageState: await page.context().storageState() });
    await blockedContext.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Storage blocked', 'SecurityError'); } }));
    const blocked = await blockedContext.newPage(), blockedErrors = [];
    blocked.on('pageerror', failure => blockedErrors.push(failure.message));
    await blocked.goto(base + '/notifications');
    await blocked.waitForFunction(() => document.body.dataset.appUnreadCount === '4');
    assert.equal(await blocked.locator('.app-notifications-page [data-app-notification-storage]').isVisible(), true);
    await blocked.locator('.app-notifications-toolbar [data-app-mark-all]').click();
    assert.equal(await blocked.locator('#app-notification-bell [data-app-unread]').isVisible(), false);
    await blocked.reload();
    await blocked.waitForFunction(() => document.body.dataset.appUnreadCount === '4');
    assert.deepEqual(blockedErrors, []);
    await blockedContext.close();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(base + '/dashboard');
    await page.waitForFunction(() => document.querySelector('#db-summary-total')?.textContent === '5');
    console.log('PASS: derived notification page/bell, capped mirrored badges, read/filter/mark-all persistence, latest-five selection, keyboard/Esc/outside focus, shared drawer, fresh midnight IDs, DST Earlier group, cross-tab and real-user isolation, blocked storage, loading/error/empty states.');
}
