import assert from 'node:assert/strict';

export async function appCalendarChecks(page, browser, base) {
    await page.setViewportSize({ width: 1440, height: 1000 });
    const dates = await page.evaluate(() => {
        const now = new Date();
        const key = delta => { const date = new Date(now.getFullYear(), now.getMonth(), now.getDate() + delta); return [String(date.getFullYear()).padStart(4, '0'), String(date.getMonth() + 1).padStart(2, '0'), String(date.getDate()).padStart(2, '0')].join('-'); };
        return { today: key(0), tomorrow: key(1), yesterday: key(-1), future: key(2), month: key(0).slice(0, 7) };
    });
    let reads = 0;
    const count = request => { if (request.method() === 'GET' && new URL(request.url()).pathname === '/api/tasks') reads++; };
    page.on('request', count);
    await page.goto(base + '/calendar?month=' + dates.month);
    await page.waitForFunction(() => document.querySelector('#app-calendar')?.getAttribute('aria-busy') === 'false');
    assert.equal(reads, 1);
    assert.equal(await page.locator('#app-calendar-grid [role="gridcell"]').count(), 42);
    assert.equal(await page.locator('#app-calendar-grid [role="columnheader"]').first().getAttribute('aria-label'), 'Monday');
    assert.equal(await page.locator('#app-calendar-grid [aria-current="date"]').count(), 1);
    assert.equal(new URL(page.url()).searchParams.get('month'), dates.month);
    await page.locator('#app-calendar-next').click();
    assert.notEqual(new URL(page.url()).searchParams.get('month'), dates.month);
    await page.locator('#app-calendar-prev').click();
    await page.locator('#app-calendar-today').click();
    assert.equal(new URL(page.url()).searchParams.get('month'), dates.month);
    assert.equal(reads, 1, 'month navigation uses the same shared array');
    const today = page.locator('#app-calendar-grid [role="gridcell"][data-app-date="' + dates.today + '"]');
    await today.focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.appDate), dates.tomorrow);
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Home');
    assert.equal(await page.locator('#app-calendar-grid [role="gridcell"][tabindex="0"]').count(), 1);
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#app-calendar-day').evaluate(node => node.matches(':popover-open')), true);
    await page.keyboard.press('Escape'); await page.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await page.waitForFunction(() => !document.querySelector('#app-calendar-day').matches(':popover-open'));
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('role')), 'gridcell');
    await today.locator('.app-calendar-pill').first().click();
    assert.equal(await page.locator('#detail-title').textContent(), 'Review task 1');
    await page.locator('#detail-close-btn').click();
    await page.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    const past = page.locator('#app-calendar-grid [role="gridcell"][data-app-date="' + dates.yesterday + '"]');
    await past.click({ position: { x: 5, y: 100 } });
    assert.equal(await page.locator('#create-modal').evaluate(node => node.open), false, 'past empty date cannot create');
    const unscheduled = page.locator('#app-calendar-unscheduled');
    await unscheduled.locator('summary').click();
    assert.equal(await unscheduled.getAttribute('open'), null);
    const future = page.locator('#app-calendar-grid [role="gridcell"][data-app-date="' + dates.future + '"]');
    await future.click({ position: { x: 5, y: 100 } });
    assert.equal(await page.locator('#app-create-due').inputValue(), dates.future);
    assert.equal(await page.locator('#app-create-due').getAttribute('min'), dates.today);
    await page.locator('#title').fill('Calendar date integration');
    const create = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/tasks'));
    await page.locator('#submit-button').click();
    const task = await (await create).json();
    await future.locator('[data-task-id="' + task.id + '"]').waitFor();
    assert.equal(await unscheduled.getAttribute('open'), null, 'collapse is preserved after refetch');
    await page.waitForFunction(() => !document.querySelector('#create-modal').open);
    assert.equal(await page.evaluate(() => document.activeElement.dataset.appDate), dates.future, 'create returns focus to its date');
    await future.locator('[data-task-id="' + task.id + '"]').click();
    await page.locator('#detail-delete-btn').click();
    await page.locator('#app-confirm-drawer-delete').click();
    await page.waitForFunction(id => !document.querySelector('.app-calendar-pill[data-task-id="' + id + '"]'), task.id);
    await unscheduled.locator('summary').click();
    await page.locator('#app-unscheduled-list [data-task-id]').first().click();
    assert.equal(await page.locator('#detail-title').textContent(), 'Review task 4');
    await page.keyboard.press('Escape'); await page.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await page.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    await page.locator('#app-calendar-today').click();
    await page.evaluate(() => { window.scrollTo(0, 0); document.activeElement?.blur(); document.querySelectorAll('.toast').forEach(node => node.remove()); });
    await page.screenshot({ path: 'storage/app/ui-review/calendar-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 380, height: 950 });
    await page.waitForFunction(() => document.querySelector('#app-calendar-desktop')?.hidden && !document.querySelector('#app-calendar-agenda')?.hidden);
    assert.equal(await page.locator('#app-calendar-desktop').isVisible(), false);
    assert.equal(await page.locator('#app-calendar-agenda').isVisible(), true);
    assert.equal(await page.locator('#app-calendar-week button').count(), 7);
    if (!await page.locator('#app-calendar-week [data-app-date="' + dates.tomorrow + '"]').count()) await page.locator('#app-calendar-next').click();
    await page.locator('#app-calendar-week [data-app-date="' + dates.tomorrow + '"]').click();
    assert.equal(await page.locator('#app-agenda-tasks .app-task-title').first().textContent(), 'Review task 2');
    await page.locator('#app-calendar-prev').click();
    assert.equal(await page.locator('#app-agenda-add').isDisabled(), true);
    await page.locator('#app-calendar-today').click();
    await page.evaluate(() => { window.scrollTo(0, 0); document.activeElement?.blur(); });
    await page.screenshot({ path: 'storage/app/ui-review/calendar-mobile.png', fullPage: true });
    await page.goto(base + '/settings');
    await page.locator('#app-settings-tab-preferences').click();
    await page.locator('#app-week-start').selectOption('sunday');
    assert.match(await page.locator('#app-settings-status').textContent(), /Preference saved/);
    await page.goto(base + '/calendar');
    await page.waitForFunction(() => document.querySelector('#app-calendar')?.getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#app-calendar-week button small').first().textContent(), 'Sun');
    await page.goto(base + '/settings');
    await page.locator('#app-settings-tab-preferences').click();
    await page.locator('#app-week-start').selectOption('monday');
    page.off('request', count);

    const context = await browser.newContext({ storageState: await page.context().storageState(), viewport: { width: 1280, height: 950 }, timezoneId: 'America/Los_Angeles' });
    const review = await context.newPage(), errors = [], consoleProblems = [];
    review.on('pageerror', error => errors.push(error.message));
    review.on('console', message => { if (['warning', 'error'].includes(message.type())) consoleProblems.push(message.text()); });
    await review.goto(base + '/calendar?month=' + dates.month);
    await review.waitForFunction(() => document.querySelector('#app-calendar')?.getAttribute('aria-busy') === 'false');
    assert.equal(await review.locator('[role="gridcell"][data-app-date="' + dates.today + '"] .app-calendar-pill-title').textContent(), 'Review task 1', 'actual Laravel date serialization keeps the original deadline in a negative timezone');
    const fixture = Array.from({ length: 7 }, (_, index) => ({ id: 700 + index, title: index === 0 ? 'Calendar <b>text</b> very long task title that must truncate safely' : 'Calendar fixture ' + index, description: 'Calendar details', status: index === 1 ? 'completed' : 'pending', stage: 'todo', priority: ['high', 'medium', 'low'][index % 3], due_date: index === 6 ? null : '2026-10-20', created_at: '2026-10-01T12:00:00Z', completed_at: index === 1 ? '2026-10-20T12:00:00Z' : null }));
    fixture[2].due_date = '2026-10-19T16:00:00.000000Z';
    let release;
    const gate = new Promise(resolve => { release = resolve; });
    await review.route('**/api/tasks?sort=deadline', async route => { await gate; await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(fixture) }); });
    await review.goto(base + '/calendar?month=2026-10');
    assert.equal(await review.locator('#app-calendar-loading').isVisible(), true);
    release();
    await review.waitForFunction(() => document.querySelector('#app-calendar')?.getAttribute('aria-busy') === 'false');
    const cell = review.locator('#app-calendar-grid [role="gridcell"][data-app-date="2026-10-20"]');
    assert.equal(await cell.locator('.app-calendar-pill').count(), 3);
    assert.equal(await cell.locator('.app-calendar-more').textContent(), '+3 more');
    assert.deepEqual(await cell.locator('.app-calendar-pill').evaluateAll(nodes => nodes.map(node => Number(node.dataset.taskId))), [700, 701, 702]);
    assert.equal(await cell.locator('b').count(), 0);
    assert.equal(await cell.locator('.app-calendar-pill-title').first().evaluate(node => node.scrollWidth > node.clientWidth), true, 'long pill title is ellipsized');
    assert.match(await cell.getAttribute('aria-label'), /6 tasks/);
    assert.equal(await cell.locator('.app-calendar-completed').count(), 1);
    await cell.locator('.app-calendar-more').click();
    assert.deepEqual(await review.locator('#app-day-tasks [data-task-id]').evaluateAll(nodes => nodes.map(node => Number(node.dataset.taskId))), [700, 701, 702, 703, 704, 705]);
    await review.locator('#app-day-tasks [data-task-id="705"] .app-task-title').click();
    assert.equal(await review.locator('#detail-title').textContent(), 'Calendar fixture 5');
    await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
    await review.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    await cell.locator('.app-calendar-more').click();
    await review.locator('#app-calendar-month').click();
    await review.waitForFunction(() => !document.querySelector('#app-calendar-day').matches(':popover-open'));
    await review.evaluate(() => { const key = 'app-settings:' + document.body.dataset.appUserId; localStorage.setItem(key, JSON.stringify({ weekStart: 'sunday' })); dispatchEvent(new StorageEvent('storage', { key })); });
    assert.equal(await review.locator('[role="columnheader"]').first().getAttribute('aria-label'), 'Sunday');
    assert.equal(new URL(review.url()).searchParams.get('month'), '2026-10');
    assert.deepEqual(errors, []); assert.deepEqual(consoleProblems, []);
    for (const theme of ['light', 'dark', 'system', 'kawaii', 'racing']) {
        await review.locator('#theme-toggle').click();
        await review.locator('.app-theme-option[data-app-mode="' + theme + '"]').click();
        await review.keyboard.press('Escape'); await review.waitForFunction(() => document.documentElement.dataset.appMobileHistoryBusy !== 'true');
        for (const width of [380, 768, 1024, 1280, 1920]) {
            await review.setViewportSize({ width, height: 950 });
            await review.waitForFunction(mobile => document.querySelector('#app-calendar-agenda')?.hidden === !mobile, width < 768);
            assert.equal(await review.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'calendar fixture overflows in ' + theme + ' at ' + width);
            assert.equal(await review.locator('#app-calendar-agenda').isVisible(), width < 768);
        }
    }
    await review.setViewportSize({ width: 1280, height: 950 });
    assert.deepEqual(errors, []); assert.deepEqual(consoleProblems, []);
    await review.unroute('**/api/tasks?sort=deadline');
    await review.route('**/api/tasks?sort=deadline', route => route.abort('failed'));
    await review.reload();
    await review.locator('#app-calendar-error').getByRole('button', { name: 'Try again' }).waitFor();
    await review.unroute('**/api/tasks?sort=deadline');
    await review.route('**/api/tasks?sort=deadline', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
    await review.locator('#app-calendar-error').getByRole('button', { name: 'Try again' }).click();
    await review.locator('#app-calendar-empty').waitFor();
    assert.match(await review.locator('#app-calendar-empty').textContent(), /Walang deadline ngayong buwan/);
    assert.equal(await review.locator('#app-calendar-grid [role="gridcell"]').count(), 42);
    await context.close();
    const blockedContext = await browser.newContext({ storageState: await page.context().storageState() });
    await blockedContext.addInitScript(() => { Storage.prototype.getItem = () => { throw Error('Blocked storage'); }; Storage.prototype.setItem = () => { throw Error('Blocked storage'); }; });
    const blocked = await blockedContext.newPage(), blockedErrors = [];
    blocked.on('pageerror', error => blockedErrors.push(error.message));
    await blocked.goto(base + '/calendar');
    await blocked.waitForFunction(() => document.querySelector('#app-calendar')?.getAttribute('aria-busy') === 'false');
    assert.equal(await blocked.locator('[role="columnheader"]').first().getAttribute('aria-label'), 'Monday');
    await blocked.goto(base + '/settings');
    await blocked.locator('#app-settings-tab-preferences').click();
    await blocked.locator('#app-week-start').selectOption('sunday');
    assert.match(await blocked.locator('#app-settings-status').textContent(), /could not be saved/);
    assert.deepEqual(blockedErrors, []);
    await blockedContext.close();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(base + '/dashboard');
    await page.waitForFunction(() => document.querySelector('#db-summary-total')?.textContent === '5');
    console.log('PASS: Calendar month URL, no navigation refetch, keyboard grid/day popover, server-order pill cap, due-date creation/past guard/focus, agenda, Unscheduled drawer, week-start setting, loading/error/empty states, local dates in a negative timezone.');
}
