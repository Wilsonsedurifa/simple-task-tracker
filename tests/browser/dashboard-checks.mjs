import assert from 'node:assert/strict';

export async function appDashboardChecks(page, browser, base) {
    await page.setViewportSize({ width: 1280, height: 800 });
    await page.evaluate(() => window.scrollTo(0, 0));
    const submitBox = await page.locator('#app-quick-submit').boundingBox();
    assert.ok(submitBox && submitBox.y + submitBox.height <= 800, 'quick add is above the fold at 1280x800');
    assert.equal(await page.locator('.app-dashboard-side').evaluate(node => getComputedStyle(node).position), 'sticky');
    assert.equal(Math.round((await page.locator('.app-dashboard-side').boundingBox()).width), 340);
    assert.ok((await page.locator('#db-summary-chart').boundingBox()).height <= 200);
    for (const [metric, due] of [['today', 'today'], ['overdue', 'overdue']]) {
        const url = new URL(await page.locator('[data-app-metric="' + metric + '"]').getAttribute('href'), base);
        assert.equal(url.searchParams.get('status'), 'pending'); assert.equal(url.searchParams.get('due'), due);
    }
    assert.match(await page.locator('#db-greeting').textContent(), /^Magandang (umaga|hapon|gabi), UI$/);
    assert.equal(await page.locator('#db-summary-pending').textContent(), '4');
    assert.equal(await page.locator('#db-summary-overdue').textContent(), '1');
    assert.equal(await page.locator('#db-summary-today').textContent(), '1');
    assert.equal(await page.locator('#db-summary-chart .app-chart-column').count(), 7);
    assert.equal(await page.locator('#app-chart-table tr').count(), 7);
    assert.equal(await page.locator('#app-week-strip button').count(), 7);
    await page.locator('#app-week-strip button').first().click();
    assert.equal(await page.locator('#app-deadline-list [data-task-id]').count(), 1);
    assert.ok(await page.locator('#app-deadline-list').getByText('Review task 1', { exact: true }).count());
    await page.locator('#app-week-actions .app-overdue-filter').click();
    assert.ok(await page.locator('#app-deadline-list').getByText('Review task 0', { exact: true }).count());
    await page.locator('#app-week-actions').getByRole('button', { name: 'All dates', exact: true }).click();
    assert.deepEqual(await page.locator('#app-deadline-list .app-side-group').allTextContents(), ['Overdue', 'Today', 'Tomorrow', 'This week']);
    await page.locator('#app-tab-deadlines').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#app-tab-active').getAttribute('aria-selected'), 'true');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('.app-dashboard-grid')?.getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#app-tab-active').getAttribute('aria-selected'), 'true');
    const title = 'Dashboard quick add <b>safe</b>';
    await page.locator('#app-quick-title').fill(title);
    await page.locator('#app-quick-priority').selectOption('high');
    await page.locator('#app-quick-toggle').click();
    const description = 'First line\nSecond line';
    await page.locator('#app-quick-description').fill(description);
    const createdResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/tasks'));
    await page.locator('#app-quick-description').press('Control+Enter');
    const created = await createdResponse;
    assert.equal(created.status(), 201);
    assert.ok(await created.request().headerValue('x-csrf-token'));
    const task = await created.json();
    await page.waitForFunction(() => document.querySelector('#db-summary-total').textContent === '6');
    assert.equal(await page.locator('#app-no-deadline').textContent(), '+1 without a deadline');
    const sideRow = page.locator('#app-active-list [data-task-id="' + task.id + '"]');
    assert.equal(await sideRow.locator('.app-task-title').textContent(), title);
    assert.equal(await sideRow.locator('b').count(), 0, 'task title is text, not markup');
    await sideRow.click();
    assert.equal(await page.locator('#detail-description').textContent(), description);
    await page.locator('#app-detail-start').click();
    await page.waitForFunction(() => document.querySelector('#detail-status-text').textContent === 'In progress');
    await page.waitForFunction(() => !document.querySelector('#app-detail-start')?.disabled);
    await page.locator('#detail-close-btn').click();
    await page.waitForFunction(() => !document.querySelector('#app-task-dialog').open);
    const progressCard = page.locator('#app-inprogress-cards [data-task-id="' + task.id + '"]');
    await progressCard.waitFor();
    await page.route('**/api/tasks/' + task.id + '/complete', async route => { await new Promise(resolve => setTimeout(resolve, 800)); await route.continue(); });
    const complete = page.waitForResponse(response => response.url().endsWith('/api/tasks/' + task.id + '/complete'));
    await progressCard.locator('[data-action="toggle-check"]').click();
    assert.equal(await page.locator('#db-summary-completed').textContent(), '2', 'optimistic completion updates stats');
    assert.equal(await page.locator('#sidebar-task-count').textContent(), '4');
    assert.equal(await page.locator('#db-summary-progress').getAttribute('aria-valuetext'), '2 of 6 completed');
    assert.equal(await page.locator('#db-chart-total').textContent(), '2 completed in the last 7 days');
    await complete;
    await page.unroute('**/api/tasks/' + task.id + '/complete');
    await page.locator('#app-tab-done').click();
    await page.waitForFunction(id => !document.querySelector('#app-done-list [data-task-id="' + id + '"] button')?.disabled, task.id);
    await page.locator('#app-done-list [data-task-id="' + task.id + '"]').click();
    await page.locator('#detail-delete-btn').click();
    await page.locator('#app-confirm-drawer-delete').click();
    await page.waitForFunction(() => document.querySelector('#db-summary-total').textContent === '5');
    await page.locator('#app-tab-deadlines').click();
    await page.evaluate(() => { window.scrollTo(0, 0); document.activeElement?.blur(); document.querySelectorAll('.toast').forEach(node => node.remove()); });
    await page.screenshot({ path: 'storage/app/ui-review/dashboard-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 380, height: 950 });
    assert.equal(await page.locator('.app-dashboard-main').isVisible(), false);
    assert.equal(await page.locator('.app-dashboard-side').isVisible(), false);
    assert.equal(await page.locator('#app-mobile-home').isVisible(), true);
    await page.screenshot({ path: 'storage/app/ui-review/dashboard-mobile.png', fullPage: true });

    // Isolated page: expected failures must not pollute clean-load console diagnostics.
    const context = await browser.newContext({ storageState: await page.context().storageState(), viewport: { width: 1280, height: 800 } });
    const review = await context.newPage(), errors = [];
    review.on('pageerror', error => errors.push(error.message));
    const fixture = Array.from({ length: 20 }, (_, index) => ({ id: 9000 + index, title: 'Fixture ' + index, description: null, status: index < 10 ? 'pending' : 'completed', stage: 'in_progress', priority: 'medium', due_date: null, created_at: Date.now(), completed_at: index < 10 ? null : Date.now() - index * 60000 }));
    await review.route('**/api/tasks?sort=deadline', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(fixture) }));
    await review.goto(base + '/dashboard');
    await review.waitForFunction(() => document.querySelector('#db-summary-total').textContent === '20');
    assert.equal(await review.locator('#app-inprogress-cards [data-task-id]').count(), 4);
    await review.locator('#app-tab-active').click();
    assert.deepEqual(await review.locator('#app-active-list [data-task-id]').evaluateAll(rows => rows.map(row => Number(row.dataset.taskId))), fixture.slice(0, 8).map(task => task.id));
    await review.locator('#app-tab-done').click();
    assert.deepEqual(await review.locator('#app-done-list [data-task-id]').evaluateAll(rows => rows.map(row => Number(row.dataset.taskId))), fixture.filter(task => task.id >= 9010 && task.id <= 9017).map(task => task.id));
    await review.route('**/api/tasks/9000/complete', async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ message: 'Dashboard rollback test' }) }); });
    await review.locator('#app-inprogress-cards [data-task-id="9000"] [data-action="toggle-check"]').click();
    assert.equal(await review.locator('#db-summary-completed').textContent(), '11');
    await review.getByText('Dashboard rollback test', { exact: true }).waitFor();
    assert.equal(await review.locator('#db-summary-completed').textContent(), '10');
    assert.equal(await review.locator('#sidebar-task-count').textContent(), '10');
    await review.locator('#app-quick-title').fill('');
    await review.locator('#app-quick-title').press('Enter');
    await review.locator('#app-quick-title[aria-invalid="true"]').waitFor();
    assert.ok(await review.locator('#app-quick-error-title').isVisible());
    await review.unroute('**/api/tasks?sort=deadline');
    await review.route('**/api/tasks?sort=deadline', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
    await review.reload();
    await review.waitForFunction(() => document.querySelector('.app-dashboard-grid')?.getAttribute('aria-busy') === 'false');
    assert.equal(await review.locator('#db-summary-chart .app-chart-column').count(), 7);
    assert.equal(await review.locator('#app-chart-table tr').count(), 7);
    assert.equal(await review.locator('.app-dashboard-stat.app-metric-positive').count(), 0);
    assert.equal(await review.locator('#app-dashboard-first-run').textContent(), 'Add a task to get started');
    for (const tab of ['deadlines', 'active', 'done']) { await review.locator('#app-tab-' + tab).click(); assert.ok(await review.locator('#app-panel-' + tab + ' .app-dashboard-empty').isVisible()); }
    assert.deepEqual(errors, []);
    await context.close();
    await page.setViewportSize({ width: 1440, height: 1000 });
    console.log('PASS: dashboard quick add above fold, inline validation, chart/table, week filters, keyboard/persisted tabs, shared drawer/cards, optimistic widget updates/rollback, latest-eight selection, first-run empty states.');
}
