import assert from 'node:assert/strict';
import { appCalendarDate, appCalendarMonth, appCalendarMonthKey, appCalendarDays, appCalendarWeek, appCalendarBuckets } from '../../resources/js/modules/app-calendar-data.js';
import { appDateInput, appDateOnly, appMinimumDueDate } from '../../resources/js/modules/app-dates.js';

const fallback = new Date(2026, 9, 15);
for (const invalid of [null, '', '2026-00', '2026-13', 'garbage', '2026-1', '0000-01']) assert.equal(appCalendarMonthKey(appCalendarMonth(invalid, fallback)), '2026-10');
assert.equal(appCalendarMonthKey(appCalendarMonth('2028-02')), '2028-02');
const leap = appCalendarDays(appCalendarMonth('2028-02'), 1);
assert.equal(leap.length, 42);
assert.equal(leap[0].getDay(), 1);
assert.ok(leap.some(date => appDateInput(date) === '2028-02-29'));
assert.equal(appCalendarDays(appCalendarMonth('2026-11'), 0)[0].getDay(), 0);
assert.equal(appDateInput(appCalendarDays(appCalendarMonth('2026-11'), 1)[0]), '2026-10-26');
assert.equal(appDateInput(appCalendarDate(2026, 12, 1)), '2027-01-01');
assert.equal(appDateInput(appCalendarDate(1, 0, 1)), '0001-01-01');
const week = appCalendarWeek(new Date(2026, 9, 15), 1);
assert.equal(week.length, 7);
assert.equal(appDateInput(week[0]), '2026-10-12');
assert.equal(appDateInput(week[6]), '2026-10-18');
const ordered = [{ id: 8, due_date: '2026-10-20' }, { id: 2, due_date: '2026-10-20' }, { id: 1, due_date: null }];
assert.deepEqual(appCalendarBuckets(ordered).get('2026-10-20').map(task => task.id), [8, 2]);
assert.equal(appCalendarBuckets(ordered).has(''), false);
assert.deepEqual(ordered.map(task => task.id), [8, 2, 1]);
assert.equal(appDateOnly('2026-10-19T16:00:00.000000Z', 'Asia/Manila'), '2026-10-20');
assert.equal(appDateOnly('2026-10-20', 'America/Los_Angeles'), '2026-10-20');
assert.ok(appMinimumDueDate('Asia/Manila', new Date(2026, 9, 15, 23)) >= '2026-10-15');
assert.equal(appMinimumDueDate('Asia/Manila', new Date(Date.UTC(2026, 9, 15, 23))), '2026-10-16');
for (const date of appCalendarDays(appCalendarMonth('2026-03'))) assert.equal(date.getHours(), 0, 'calendar arithmetic preserves local midnight across DST');
console.log('PASS: month parsing, leap day, Monday/Sunday starts, local day/week arithmetic, year boundaries, and server-ordered date buckets.');
