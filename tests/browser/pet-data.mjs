import assert from 'node:assert/strict';
import { appPetMood, appPetBadges } from '../../resources/js/modules/app-pet-data.js';
const today = new Date(2026, 9, 15, 12), pet = { name: '<Mochi>', level: 3, longest_streak: 4, completed_count: 5 };
const pending = date => ({ status: 'pending', due_date: date });
const done = date => ({ status: 'completed', completed_at: date });
assert.equal(appPetMood([], pet, today).mood, 'sleepy');
assert.equal(appPetMood([done(new Date(2026, 9, 14, 12))], pet, today).mood, 'proud');
assert.equal(appPetMood([done(today), pending('2026-10-16')], pet, today).mood, 'happy');
assert.equal(appPetMood([pending('2026-10-14')], pet, today).mood, 'worried');
assert.equal(appPetMood([pending('2026-10-14'), pending('2026-10-13')], pet, today).mood, 'worried');
assert.equal(appPetMood(Array.from({ length: 3 }, () => pending('2026-10-14')), pet, today).mood, 'sad');
assert.equal(appPetMood([pending('2026-10-15'), done(new Date(2026, 9, 14, 23, 59))], pet, today).mood, 'sleepy');
const tasks = Object.freeze([Object.freeze(pending('2026-10-16')), Object.freeze(done(today))]);
assert.match(appPetMood(tasks, pet, today).text, /^<Mochi> is happy:/);
assert.deepEqual(tasks.map(task => task.status), ['pending', 'completed']);
const badges = appPetBadges(tasks, pet, today);
assert.equal(badges.length, 6); assert.equal(badges.filter(badge => badge.unlocked).length, 5);
assert.equal(appPetBadges([], { ...pet, completed_count: 0 }, today).at(-1).unlocked, false);
console.log('PASS: pure pet mood precedence, local dates, instant overdue recovery, escaped-as-text names, immutable server order, six derived badge thresholds.');
